/**
 * dwy 命令行帮助文案。
 * 已实现的入口必须出现在这里；禁止把可用命令藏进「隐藏」段。
 */

/**
 * 主帮助：`dwy --help`。
 * version 来自 package.json，调用方传入，避免本模块读盘。
 *
 * @param {string} version
 */
export function buildHelpText(version) {
  return [
    `dwy ${version}`,
    '',
    '用法：',
    '  dwy            选择范围、配置和 CLI，预览清单后同步',
    '  dwy sync       同上',
    '  dwy upgrade    升级到 npm 最新正式版，并刷新共享 Skills',
    '  dwy refresh    用当前 CLI 包内模板刷新已安装的共享 Skills',
    '  dwy migrate    一键迁移老项目已有的托管 Skills，原目录先备份',
    '  dwy --help     显示本说明',
    '  dwy --version  显示版本',
    '',
    '同步步骤：',
    '  1. 选择同步范围：当前项目或全局。',
    '  2. 选择 Skills。',
    '  3. 选择 AGENTS.md 通用规范，默认启用。',
    '  4. 选择 Hooks，默认启用。',
    '     项目已有有效全局规范或全部所需全局 Hooks 时，跳过对应操作页。',
    '  5. 最后选择 CLI；首次只选 Codex，后续恢复当前范围同步过的 CLI 与有效旧托管入口。',
    '  6. 按最终 CLI 重新核算覆盖，预览实际写入、迁移、备份和清理清单。',
    '  7. 确认后执行，显示实际完成信息；取消不改同步目标。',
    '  Commands 不参与同步。',
    '',
    '交互按键：',
    '  Skills：←/→ 切分类，↑/↓ 移动，Space 勾选，a 全选／清空当前分类。',
    '  范围 / 通用规范 / Hooks / CLI：↑/↓ 移动；CLI 用 Space 勾选，可输入关键字筛选。',
    '  Enter 确认当前步骤，Esc 或 Ctrl+C 取消。',
    '',
    '常见用法：',
    '  同步当前项目：cd your-project 后执行 dwy，选择「当前项目」。',
    '  同步全局：执行 dwy，选择「全局」。',
    '  移除配置：在当前范围取消 Skills 勾选，或关闭 Hooks / 通用规范，再确认。',
    '  更新或调整配置：再次执行 dwy sync，检查勾选项，再确认同步。',
    '  更新 CLI：dwy upgrade（全局安装时可用；更新后执行 dwy --version 查看版本）。',
    '  迁移老项目：cd your-project 后执行 dwy migrate，无需重新勾选。',
    '  只更新 Skills：执行 dwy refresh，所有已迁移的链接同时生效。',
    '  首次安装：npm install -g create-dwy@latest',
    '',
    '平台支持：',
    '  Claude Code：全局 ~/.claude/CLAUDE.md；项目可使用根 AGENTS.md。',
    '  Codex：全局 $CODEX_HOME/AGENTS.md（默认 ~/.codex/AGENTS.md）；项目根 AGENTS.md。',
    '  OpenCode：全局 ~/.config/opencode/AGENTS.md；项目根 AGENTS.md；当前不支持 Hooks。',
    '',
    '同步按当前范围和最终 CLI 执行；项目 AGENTS.md 由多个 CLI 共享。',
    '用户主目录不能作为项目范围同步，请选择全局或进入项目目录。',
    '关闭选项只移除当前范围托管内容；项目操作不移除全局配置。',
    'Skills 副本集中在 ~/.dwy/skills；项目和全局使用目录链接，同平台全局入口优先。',
    '项目 Skills 全部适用平台均有有效全局入口时显示「全局已启用」，不能重复勾选。',
    '部分平台已有有效全局入口时仍可选，只为缺少全局入口的平台安装项目链接。',
    'Hooks 与 Skills 独立；整组管理，项目仅安装缺少有效全局注册的 Hooks。',
    '全局 Hook 的脚本与对应事件、matcher、完整命令注册均有效时，项目禁止重复安装。',
    '任一适用 CLI 已有 dwy 全局通用规范时，项目继承并清理重复基线；其他 CLI 缺失的全局规范另选全局范围补齐。',
    '手写 AGENTS.md 本身不算全局已安装；通用规范仅管理其托管块，保留手写内容。',
    '旧托管 Rules 确认后清理，Skills 自行选择；无法确认归属的内容保留。',
    '全局启用会明确列出当前项目重复项清理；全局移除不会自动向项目补装。',
    '项目同步只清理项目重复入口，不改写有效全局提供者；真实目录先备份。',
    '确认前不改项目／全局配置或已安装共享内容；确认后才同步配置，并刷新所选共享 Skills。',
    '由有效全局入口提供的 Skills 不借项目同步改写；全部已安装副本用 dwy refresh 更新。',
    'sync / migrate 脚本接口仍须显式指定范围。',
    '产品流程缺失的外部依赖也列入清单，确认后联网补齐，已有内容保留。',
    '旧真实目录备份到同步根的 .dwy/skill-backups；个人 Skills、Rules、Hooks 不参与 migrate。',
    '旧项目首次需执行 dwy migrate；迁移后无需逐项目刷新 Skills。',
    'Hooks 的模板更新仍需执行 dwy sync；已有会话缓存的 Skill 可能需要重新加载。',
    '',
    '模板更新：',
    '  模板随 CLI 包分发，启动不联网检查模板。',
    '  DWY_TEMPLATE_SOURCE_DIR 开发覆盖优先；未设置时读取当前 CLI 的 dwy-cli/templates/ai-tools。',
    '  Skills 新增或变更需要 CLI 发版；dwy upgrade 更新程序与包内模板。',
    '',
  ].join('\n')
}
